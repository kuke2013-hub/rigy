import assert from 'node:assert/strict';
import fs from 'node:fs';
import {constrainAnatomicalAngles as limit,getJointProfile} from '../anatomy/constraint-core.mjs';
const data=JSON.parse(fs.readFileSync(new URL('../anatomy/medical-joints.v1.json',import.meta.url)));
const joint=name=>getJointProfile(data,name);
const elbow=limit(joint('elbow'),{flexion:200,twist:44,abduction:20});
assert.deepEqual(elbow,{flexion:145,twist:0,abduction:0});
const knee=joint('knee');
assert.equal(limit(knee,{flexion:5,twist:99}).twist,23);
assert.equal(limit(knee,{flexion:5,twist:-99}).twist,-10);
assert.equal(limit(knee,{flexion:60,twist:99}).twist,45);
assert.equal(limit(knee,{flexion:0,twist:99}).twist,0);
const wrist=joint('wrist');
const wr=limit(wrist,{flexion:74,abduction:20});
assert(wr.flexion<74 && wr.abduction<=20,'2-axis wrist movement is coupled');
const fingers=limit(joint('fingerMCP'),{flexion:86,abduction:15});
assert.equal(fingers.abduction,0,'MCP spreading should diminish during full prototype flexion');
assert.throws(()=>getJointProfile(data,'cervicalGlobal'),/aggregate/);
assert.throws(()=>getJointProfile(data,'subtalar'),/not calibrated/);
assert.throws(()=>limit(joint('hip'),{flexion:NaN}),/Non-finite/);
console.log('PASS: 8 medical-reference prototype constraint assertions');
